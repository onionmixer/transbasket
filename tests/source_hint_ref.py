LATIN, MARK, IGNORE = "Latin", "Mark", "Ignore"
BUCKETS = ["Hangul", "Kana", "Han", "Latin", "Cyrillic", "Greek", "Hebrew", "Arabic",
           "Thai", "Devanagari", "Georgian", "Armenian", "Other"]


def check_table():
    for (c1, a1, b1), (c2, a2, b2) in zip(TABLE, TABLE[1:]):
        assert a1 <= b1 and b1 < a2, f"overlap/order: {c1} {a1:X}-{b1:X} vs {c2} {a2:X}-{b2:X}"
    for c, _, _ in TABLE:
        assert c in BUCKETS or c == MARK, c


def class_of(cp):
    """Binary search over the sorted table; anything not listed is Ignore."""
    if cp == INVALID:
        return IGNORE
    lo, hi = 0, len(TABLE) - 1
    while lo <= hi:
        mid = (lo + hi) // 2
        c, a, b = TABLE[mid]
        if cp < a:
            hi = mid - 1
        elif cp > b:
            lo = mid + 1
        else:
            return c
    return IGNORE


# ---------------------------------------------------------------- counting
def count_units(data: bytes):
    """Latin: one unit per run of Latin letters (combining marks continue a run).
    Everything else: one unit per codepoint. INVALID, IGNORE and stray marks
    end a run and count nothing."""
    counts = dict.fromkeys(BUCKETS, 0)
    in_latin = False
    for cp in decode(data):
        c = class_of(cp)
        if c == LATIN:
            if not in_latin:
                counts["Latin"] += 1
            in_latin = True
        elif c == MARK and in_latin:
            pass
        else:
            in_latin = False
            if c not in (MARK, IGNORE):
                counts[c] += 1
    return counts


TOP_LANG = {"Hangul": "kor", "Japanese": "jpn", "Han": "chi", "Thai": "tha",
            "Greek": "gre", "Georgian": "geo", "Armenian": "arm"}   # shared scripts -> und


def _merged(counts, kana_rule):
    g = {k: v for k, v in counts.items() if v}
    kana, han = counts["Kana"], counts["Han"]
    if kana and kana_rule(kana, han):
        g["Japanese"] = kana + han
        g.pop("Kana", None); g.pop("Han", None)
    return g


def classify(data: bytes):
    """Fallback hint: (lang, mixed). Any Kana makes the Han+Kana block Japanese."""
    g = _merged(count_units(data), lambda kana, han: True)
    total = sum(g.values())
    if total == 0:
        return ("und", False)
    ranked = sorted(g.values(), reverse=True)
    top_n = ranked[0]
    tops = [k for k, v in g.items() if v == top_n]
    second = ranked[1] if len(ranked) > 1 else 0
    mixed = 100 * second >= 30 * total
    if len(tops) > 1:
        return ("und", mixed)                # tie
    return (TOP_LANG.get(tops[0], "und"), mixed)


# ---------------------------------------------------------------- model check
REQUIRED = {"kor": {"Hangul", "Han"}, "jpn": {"Kana", "Han"}, "chi": {"Han"}, "zhs": {"Han"},
            "zht": {"Han"}, "tha": {"Thai"}, "gre": {"Greek"}, "heb": {"Hebrew"}, "yid": {"Hebrew"},
            "geo": {"Georgian"}, "arm": {"Armenian"}, "rus": {"Cyrillic"}, "ukr": {"Cyrillic"},
            "bul": {"Cyrillic"}, "bel": {"Cyrillic"}}
DOMINANT = {"Hangul": {"kor"}, "Japanese": {"jpn"}, "Thai": {"tha"}, "Greek": {"gre"},
            "Georgian": {"geo"}, "Armenian": {"arm"}, "Hebrew": {"heb", "yid"}}


def model_contradicted(data: bytes, lang: str) -> bool:
    """True only when script evidence rules the model's code out."""
    counts = count_units(data)
    need = REQUIRED.get(lang)
    if need and sum(counts[s] for s in need) == 0:
        return True
    # Japanese counts as dominant only with real Kana evidence (>= 20% of Han+Kana).
    g = _merged(counts, lambda kana, han: 5 * kana >= kana + han)
    total = sum(g.values())
    for script, allowed in DOMINANT.items():
        if total and 100 * g.get(script, 0) >= 95 * total and lang not in allowed:
            return True
    return False


