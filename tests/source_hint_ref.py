"""Reference specification of the source_hint script classifier, version 1.

This file is the normative spec for PLAN_SOURCE_HINT_METADATA.md section 5.
The C implementation must produce identical results for every byte string of
at most 10,000 bytes (MAX_TEXT_LENGTH) passed as pointer + length - embedded
NUL bytes included; with that bound 64-bit counters cannot overflow 100 * n.
Everything here is integer arithmetic over the checked-in range table
(tests/source_hint_table.py, frozen at Unicode 13.0.0) - no locale and no
runtime unicodedata.
"""

HINT_VERSION = 1

# ---------------------------------------------------------------- decoding
# Strict UTF-8 (Unicode Table 3-7). An ill-formed sequence yields INVALID and
# advances exactly one byte, so C and Python resynchronise identically.
INVALID = -1


def decode(data: bytes):
    i, n = 0, len(data)
    while i < n:
        b = data[i]
        if b < 0x80:
            yield b; i += 1; continue
        if 0xC2 <= b <= 0xDF:
            need, lo, hi = 1, 0x80, 0xBF
        elif b == 0xE0:
            need, lo, hi = 2, 0xA0, 0xBF
        elif 0xE1 <= b <= 0xEC or 0xEE <= b <= 0xEF:
            need, lo, hi = 2, 0x80, 0xBF
        elif b == 0xED:
            need, lo, hi = 2, 0x80, 0x9F          # no surrogates
        elif b == 0xF0:
            need, lo, hi = 3, 0x90, 0xBF
        elif 0xF1 <= b <= 0xF3:
            need, lo, hi = 3, 0x80, 0xBF
        elif b == 0xF4:
            need, lo, hi = 3, 0x80, 0x8F          # <= U+10FFFF
        else:
            yield INVALID; i += 1; continue
        cp = b & (0x7F >> (need + 1))
        good = True
        for k in range(1, need + 1):
            if i + k >= n:
                good = False; break
            c = data[i + k]
            if k == 1:
                if not (lo <= c <= hi):
                    good = False; break
            elif not (0x80 <= c <= 0xBF):
                good = False; break
            cp = (cp << 6) | (c & 0x3F)
        if not good:
            yield INVALID; i += 1; continue
        yield cp
        i += need + 1


