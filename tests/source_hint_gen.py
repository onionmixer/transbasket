"""Generate tests/source_hint_table.py, the frozen classification table of the
source_hint classifier (PLAN_SOURCE_HINT_METADATA.md section 5).

    python3 -I tests/source_hint_gen.py

Run deliberately, never at build time: the output is checked in so that the C
port and the Python reference share one literal table. Regenerating with a
different Unicode version changes classifications and therefore requires a new
HINT_VERSION.

Rule: a codepoint is a script unit only when its General Category is a letter
(L*) or a mark (M*) AND it lies in one of the listed script ranges. Letters and
marks outside every listed range are "Other". Combining Diacritical Marks
(U+0300-036F) are "Mark" (they continue a Latin word). Everything else -
digits, punctuation, symbols, separators, format, unassigned - is not listed
and therefore classifies as Ignore.
"""
import os
import sys
import unicodedata

UNICODE_VERSION = "13.0.0"

SCRIPT_RANGES = {
    "Latin": [(0x41, 0x5A), (0x61, 0x7A), (0xAA, 0xAA), (0xBA, 0xBA), (0xC0, 0x24F), (0x250, 0x2AF),
              (0x1E00, 0x1EFF), (0x2C60, 0x2C7F), (0xA720, 0xA7FF), (0xFF21, 0xFF3A), (0xFF41, 0xFF5A)],
    "Greek": [(0x370, 0x3FF), (0x1F00, 0x1FFF)],
    "Cyrillic": [(0x400, 0x52F)],
    "Armenian": [(0x530, 0x58F), (0xFB13, 0xFB17)],
    "Hebrew": [(0x590, 0x5FF), (0xFB1D, 0xFB4F)],
    "Arabic": [(0x600, 0x6FF), (0x750, 0x77F), (0x8A0, 0x8FF), (0xFB50, 0xFDFF), (0xFE70, 0xFEFF)],
    "Devanagari": [(0x900, 0x97F)],
    "Thai": [(0xE00, 0xE7F)],
    "Georgian": [(0x10A0, 0x10FF), (0x2D00, 0x2D2F)],
    "Hangul": [(0x1100, 0x11FF), (0x3130, 0x318F), (0xA960, 0xA97F), (0xAC00, 0xD7AF), (0xD7B0, 0xD7FF),
               (0xFFA0, 0xFFDC)],
    "Kana": [(0x3040, 0x309F), (0x30A0, 0x30FF), (0x31F0, 0x31FF), (0xFF66, 0xFF9F), (0x1B000, 0x1B0FF)],
    # U+3005-3006 (iteration mark, closing mark) sit in CJK Symbols but are written inside Han words.
    "Han": [(0x3005, 0x3006), (0x3400, 0x4DBF), (0x4E00, 0x9FFF), (0xF900, 0xFAFF), (0x20000, 0x2FA1F),
            (0x30000, 0x3134F)],
}
MARK_RANGE = (0x300, 0x36F)


def classify_codepoint(cp, script_of):
    if 0xD800 <= cp <= 0xDFFF:
        return None
    if MARK_RANGE[0] <= cp <= MARK_RANGE[1]:
        return "Mark"
    if unicodedata.category(chr(cp))[0] not in "LM":
        return None
    return script_of.get(cp, "Other")


def build():
    if unicodedata.unidata_version != UNICODE_VERSION:
        sys.exit(f"unicodedata {unicodedata.unidata_version} != frozen {UNICODE_VERSION}; refusing to regenerate")
    script_of = {}
    for script, ranges in SCRIPT_RANGES.items():
        for lo, hi in ranges:
            for cp in range(lo, hi + 1):
                if cp in script_of:
                    sys.exit(f"U+{cp:04X} listed for both {script_of[cp]} and {script}")
                script_of[cp] = script
    table, current, start = [], None, 0
    for cp in range(0x110000 + 1):
        cls = classify_codepoint(cp, script_of) if cp <= 0x10FFFF else "<end>"
        if cls != current:
            if current is not None:
                table.append((current, start, cp - 1))
            current, start = cls, cp
    return table


def main():
    table = build()
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "source_hint_table.py")
    with open(out, "w", encoding="utf-8") as fp:
        fp.write('"""GENERATED by tests/source_hint_gen.py - do not edit.\n\n')
        fp.write(f"Unicode {UNICODE_VERSION}. (class, first, last) inclusive, sorted, non-overlapping.\n")
        fp.write('Codepoints not covered by any range classify as Ignore.\n"""\n')
        fp.write(f"UNICODE_VERSION = {UNICODE_VERSION!r}\n\nTABLE = [\n")
        for cls, lo, hi in table:
            fp.write(f"    ({cls!r}, 0x{lo:04X}, 0x{hi:04X}),\n")
        fp.write("]\n")
    print(f"wrote {out}: {len(table)} ranges (Unicode {UNICODE_VERSION})")


if __name__ == "__main__":
    main()
