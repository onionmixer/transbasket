"""Differential test: C classifier (src/source_hint.c) vs the normative
reference tests/source_hint_ref.py.

    python3 -I tests/test_source_hint.py obj/test_source_hint [--cases N] [--seed S]

Checks, for every generated byte string: fallback (lang, mixed), the model
contradiction verdict for one model code, UTF-8 validity and a checksum of the
decoded code points. Also checks that the C range table equals the Python one.
"""
import os
import random
import struct
import subprocess
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import source_hint_ref as R  # noqa: E402
import source_hint_eval as E  # noqa: E402

MAX_INPUT = 10000
MODEL_CODES = sorted(set(R.REQUIRED) | {"eng", "fre", "ger", "und", "ben", "tam", "spa", "vie", "per", "ara"})


def expected(data: bytes, lang):
    if len(data) > MAX_INPUT:
        g = ("ERR", False)
        contra = False if lang else None
    else:
        g = R.classify(data)
        contra = R.model_contradicted(data, lang) if lang else None
    cps = list(R.decode(data))
    checksum = sum((cp + 2) * (i + 1) for i, cp in enumerate(cps)) % (1 << 64)
    c = "-" if contra is None else ("1" if contra else "0")
    return f"{g[0]} {1 if g[1] else 0} {c} {0 if R.INVALID in cps else 1} {checksum}"


def class_samples():
    """A few code points from every class of the table, plus Ignore ones."""
    samples = {}
    for cls, lo, hi in R.TABLE:
        samples.setdefault(cls, []).extend({lo, hi, (lo + hi) // 2})
    samples["Ignore"] = [0x20, 0x21, 0x30, 0x2C, 0x3000, 0x3001, 0x037E, 0x0E50, 0x30FB, 0x1F600, 0xFF01, 0x2160]
    return samples


def generate(rnd, n):
    cases = []
    # 1. fixed cases of the evaluator
    for lang, _, text in E.FALLBACK_CASES:
        cases.append((text.encode(), None))
    for lang, _, text in E.OVERRIDE_CASES:
        cases.append((text.encode(), lang))
    # 2. every table boundary +-1, alone and inside context
    for cls, lo, hi in R.TABLE:
        for cp in (lo - 1, lo, hi, hi + 1):
            if 0 <= cp <= 0x10FFFF and not 0xD800 <= cp <= 0xDFFF:
                ch = chr(cp).encode()
                cases.append((ch, rnd.choice(MODEL_CODES)))
                cases.append((b"a" + ch + b"b", None))
                cases.append(("한".encode() + ch + "글".encode(), rnd.choice(MODEL_CODES)))
    # 3. threshold constructions (integer boundaries of 30%, 95% and Kana 20%)
    han, kana, hangul, latin = "中".encode(), "か".encode(), "한".encode(), b"w "
    for total in (20, 100, 101, 1000):
        for second in range(max(0, total * 30 // 100 - 2), total * 30 // 100 + 3):
            cases.append((hangul * (total - second) + latin * second, None))
        for top in range(total * 95 // 100 - 2, total * 95 // 100 + 3):
            if 0 <= top <= total:
                body = hangul * top + latin * (total - top)
                cases.append((body, rnd.choice(["jpn", "kor", "und", "eng"])))
    for k in range(15, 26):
        cases.append((kana * k + han * (100 - k), rnd.choice(["chi", "jpn", "kor", "und"])))
    for a in range(1, 6):
        cases.append((hangul * a + latin * a, None))             # ties
        cases.append((kana * a + "ไ".encode() * (2 * a), None))
    # 4. malformed UTF-8, NUL, decomposed accents, length limit
    for b in (b"\xc0\x80", b"\xe0\x80\x80", b"\xed\xa0\x80", b"\xf4\x90\x80\x80", b"\xe3\x81", b"\x80",
              b"\xe3\x81A", b"a\x00\xed\x95\x9c\xed\x95\x9c", b"e\xcc\x81t\xcc\x81", b"\xcc\x81a"):
        cases.append((b, rnd.choice(MODEL_CODES)))
    cases.append(("가".encode() * 3333 + b"a", "kor"))          # 10000 bytes
    cases.append(("가".encode() * 3333 + b"ab", "kor"))         # 10001 bytes: rejected
    cases.append((b"a" * MAX_INPUT, "eng"))
    # 5. random mixtures until n cases
    samples = class_samples()
    classes = list(samples)
    while len(cases) < n:
        parts = []
        for _ in range(rnd.randrange(0, 40)):
            r = rnd.random()
            if r < 0.08:
                parts.append(bytes([rnd.randrange(256)]))         # possibly ill-formed byte
            elif r < 0.16:
                parts.append(rnd.choice([b" ", b"1", b".", b"'", b"\x00", b"\n"]))
            else:
                cp = rnd.choice(samples[rnd.choice(classes)])
                parts.append(chr(cp).encode())
                if rnd.random() < 0.1:
                    parts.append("́".encode())
        cases.append((b"".join(parts), rnd.choice(MODEL_CODES + [None])))
    return cases


def main():
    binary = sys.argv[1]
    n = int(sys.argv[sys.argv.index("--cases") + 1]) if "--cases" in sys.argv else 25000
    seed = int(sys.argv[sys.argv.index("--seed") + 1]) if "--seed" in sys.argv else 20261106

    dump = subprocess.run([binary, "--dump-table"], capture_output=True, text=True, check=True).stdout.split("\n")
    c_table = [(c, int(a), int(b)) for c, a, b in (line.split() for line in dump if line)]
    table_ok = c_table == [(c, a, b) for c, a, b in R.TABLE]
    print(f"table identity: C {len(c_table)} ranges vs Python {len(R.TABLE)} -> {'identical' if table_ok else 'DIFFERENT'}")

    cases = generate(random.Random(seed), n)
    payload = b"".join(struct.pack("<I", len(d)) + d + (lang.encode() if lang else b"---") for d, lang in cases)
    out = subprocess.run([binary], input=payload, capture_output=True, check=True).stdout.decode().split("\n")
    mismatches = 0
    for (data, lang), got in zip(cases, out):
        want = expected(data, lang)
        if got != want:
            mismatches += 1
            if mismatches <= 10:
                print(f"MISMATCH lang={lang} input={data[:40]!r} C={got!r} ref={want!r}")
    if len([l for l in out if l]) != len(cases):
        print(f"RESULT COUNT {len([l for l in out if l])} != {len(cases)}")
        mismatches += 1
    print(f"differential: {len(cases)} byte strings (seed {seed}), mismatches {mismatches}")
    return 0 if table_ok and mismatches == 0 else 1


if __name__ == "__main__":
    sys.exit(main())
